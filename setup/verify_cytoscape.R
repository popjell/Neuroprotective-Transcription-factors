library(RCy3)
cytoscapePing()
print(cytoscapeVersionInfo())
nodes <- data.frame(id=c('neuro-smoke-a','neuro-smoke-b','neuro-smoke-c'))
edges <- data.frame(source=c('neuro-smoke-a','neuro-smoke-b'),target=c('neuro-smoke-b','neuro-smoke-c'),interaction='regulates')
network <- createNetworkFromDataFrames(nodes, edges, title='WSL migration smoke test', collection='Migration verification')
stopifnot(getNodeCount(network=network)==3, getEdgeCount(network=network)==2)
layoutNetwork('grid',network=network)
deleteNetwork(network=network)
cat('CYTOSCAPE RCy3 NETWORK VERIFICATION PASSED\n')